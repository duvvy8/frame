scoped_refptr<Supplier> GetThemeSupplier(scoped_refptr<Supplier> original) {
  // Reuse immutable keys across windows and WebUI. The ColorProvider owns its
  // own reference, so eviction cannot invalidate a live key or supplier.
  using Entry = std::pair<scoped_refptr<Supplier>, scoped_refptr<Supplier>>;
  static base::NoDestructor<std::list<Entry>> cache;
  for (auto it = cache->begin(); it != cache->end(); ++it) {
    if (it->first == original) {
      auto result = it->second;
      cache->splice(cache->begin(), *cache, it);
      return result;
    }
  }
  auto result = base::MakeRefCounted<FrameThemeSupplier>(original);
  cache->emplace_front(std::move(original), result);
  if (cache->size() > 16) {
    cache->pop_back();
  }
  return result;
}
